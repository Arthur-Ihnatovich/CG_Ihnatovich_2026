"""Лабораторная 3. Растровые алгоритмы.

Все функции возвращают список пикселей (x, y).
Пиксель (x, y) - это клетка сетки с центром в точке (x, y).
Если передать список log, в него пишутся промежуточные вычисления (их видно в окне программы).
Строки с log на результат не влияют, а при замере времени log не передается.
"""
import math


def round_half_up(value):
    """Обычное округление: 2.5 -> 3 (встроенный round() дает 2)."""
    return math.floor(value + 0.5)              # 2.4 -> 2.9 -> 2, 2.5 -> 3.0 -> 3, 2.6 -> 3.1 -> 3


def show(value):
    """Число для лога: 4 знака после точки, а если это ничья (x.5) - все знаки."""
    if abs(value - math.floor(value) - 0.5) < 1e-9:     # дробная часть почти ровно 0.5
        return repr(value)                              # все знаки, например 0.4999999999999999
    return f"{value:.4f}"                               # обычно 4 знака, например 0.4286


# 1. Пошаговый алгоритм
def step_by_step(x1, y1, x2, y2, log=None):
    """Идем с шагом 1 по длинной оси, вторую координату считаем по уравнению прямой."""
    dx, dy = x2 - x1, y2 - y1                   # насколько отрезок сдвигается по x и по y (со знаком)
    if dx == 0 and dy == 0:
        return [(x1, y1)]                       # отрезок-точка, иначе ниже было бы деление на 0
    points = []
    if abs(dx) >= abs(dy):                      # пологий отрезок, шагаем по x
        k = dy / dx                             # наклон: на сколько растет y, когда x растет на 1
        b = y1 - k * x1                         # чтобы прямая y = kx + b прошла через (x1, y1)
        if log is not None:
            log.append(f"k = {dy}/{dx} = {k:.4f}, b = {b:.4f}")
            log.append("   x |       y | пиксель")
        step = 1 if dx > 0 else -1              # идем вправо или влево
        for x in range(x1, x2 + step, step):    # x от x1 до x2 включительно (range не включает конец)
            y = k * x + b                       # точная высота прямой в этом столбце
            points.append((x, round_half_up(y)))    # берем ближайшую клетку
            if log is not None:
                log.append(f"{x:4} | {show(y):>7} | ({x}, {round_half_up(y)})")
    else:                                       # крутой отрезок, шагаем по y
        k = dx / dy                             # здесь x = k*y + b
        b = x1 - k * y1                         # прямая проходит через (x1, y1)
        if log is not None:
            log.append(f"крутой: x = k*y + b, k = {dx}/{dy} = {k:.4f}, b = {b:.4f}")
            log.append("   y |       x | пиксель")
        step = 1 if dy > 0 else -1              # идем вверх или вниз
        for y in range(y1, y2 + step, step):    # y от y1 до y2 включительно
            x = k * y + b                       # точный x прямой в этой строке
            points.append((round_half_up(x), y))    # берем ближайшую клетку
            if log is not None:
                log.append(f"{y:4} | {show(x):>7} | ({round_half_up(x)}, {y})")
    return points


# 2. ЦДА
def dda(x1, y1, x2, y2, log=None):
    """ЦДА: делаем L шагов и каждый раз прибавляем к x и y одни и те же dx/L и dy/L."""
    dx, dy = x2 - x1, y2 - y1                   # насколько отрезок сдвигается по x и по y
    length = max(abs(dx), abs(dy))              # L: длина по длинной оси = число шагов
    if length == 0:
        return [(x1, y1)]                       # отрезок-точка, иначе ниже было бы деление на 0
    x_inc, y_inc = dx / length, dy / length     # сдвиг за шаг: по длинной оси ровно 1, по другой <= 1
    if log is not None:
        log.append(f"L = {length}, dx/L = {x_inc:.4f}, dy/L = {y_inc:.4f}")
        log.append("   i |       x |       y | пиксель")
    x, y = float(x1), float(y1)                 # текущая точка на прямой, дальше в ней копятся дроби
    points = []
    for i in range(length + 1):                 # точек на 1 больше, чем шагов
        points.append((round_half_up(x), round_half_up(y)))    # округлили обе координаты до пикселя
        if log is not None:
            log.append(f"{i:4} | {show(x):>7} | {show(y):>7} | ({round_half_up(x)}, {round_half_up(y)})")
        x += x_inc                              # шагнули к следующей точке прямой:
        y += y_inc                              # только сложение, без умножения
    return points


# 3. Брезенхем для отрезка
def bresenham_line(x1, y1, x2, y2, log=None):
    """Брезенхем: только целые числа. По знаку ошибки e решаем, шагать ли по второй оси."""
    dx, dy = abs(x2 - x1), abs(y2 - y1)         # длины проекций без знака
    sx = 1 if x2 >= x1 else -1                  # куда шагать по x: вправо или влево
    sy = 1 if y2 >= y1 else -1                  # куда шагать по y: вверх или вниз
    steep = dy > dx                             # крутой ли отрезок
    if steep:                                   # у крутого меняем x и y ролями:
        dx, dy = dy, dx                         # теперь dx всегда длинная проекция
    # e - насколько прямая в следующем столбце выше (+) или ниже (-) середины между
    # двумя клетками-кандидатами, умноженное на 2*dx, чтобы не было дробей
    e = 2 * dy - dx                             # e0, для отрезка (0, 0)-(7, 3) это -1
    if log is not None:
        if steep:
            log.append("крутой: главная ось y, dx и dy поменяли местами")
        log.append(f"dx = {dx}, dy = {dy}, e0 = 2*dy - dx = {e}")
        log.append(f"e < 0: прямо, e += {2 * dy}; e >= 0: по диагонали, e -= {2 * (dx - dy)}")
        log.append("   x |    y |    e | дальше")
    x, y = x1, y1                               # x и y - настоящие координаты, их не меняли местами
    points = []
    for _ in range(dx + 1):                     # пикселей на 1 больше, чем шагов
        points.append((x, y))                   # записали текущий пиксель
        if log is not None:
            log.append(f"{x:4} | {y:4} | {e:4} | {'по диагонали' if e >= 0 else 'прямо'}")
        if e >= 0:                              # прямая не ниже середины, шаг по диагонали:
            if steep:
                x += sx                         # у крутого вторая ось x
            else:
                y += sy                         # у пологого вторая ось y
            e += 2 * (dy - dx)                  # e уменьшается на 2(dx - dy)
        else:                                   # прямая ниже середины, шаг прямо:
            e += 2 * dy                         # по второй оси не двигаемся, e растет на 2dy
        if steep:                               # по главной оси шагаем всегда:
            y += sy                             # у крутого по y
        else:
            x += sx                             # у пологого по x
    return points


# 4. Брезенхем для окружности
def bresenham_circle(xc, yc, r, log=None):
    """Брезенхем для окружности: считаем 1/8 (от (0, R) до x = y), остальное отражаем."""
    # Считаем окружность с центром в (0, 0), а центр (xc, yc) прибавляем при записи точек.
    # На дуге от (0, R) до x = y координата x растет на 1, а y остается тем же
    # (кандидат A = (x+1, y)) или уменьшается на 1 (кандидат B = (x+1, y-1)).
    # d = F(A) + F(B), где F(x, y) = x^2 + y^2 - R^2: снаружи окружности F > 0, внутри F < 0.
    # d < 0 - ближе A, иначе ближе B.
    x, y = 0, r                                 # старт: верхняя точка (0, R)
    d = 3 - 2 * r                               # d0 = F(1, R) + F(1, R - 1) = 1 + (2 - 2R)
    points = []
    if log is not None:
        log.append(f"центр ({xc}, {yc}), R = {r}, d0 = 3 - 2R = {d}")
        log.append("d < 0: d += 4x + 6; иначе d += 4(x - y) + 10 и y - 1")
        log.append("   x |    y |    d | дальше")
    while x <= y:                               # пока не дошли до диагонали x = y (1/8 окружности)
        for px, py in ((x, y), (y, x), (-x, y), (-y, x), (x, -y), (y, -x), (-x, -y), (-y, -x)):
            points.append((xc + px, yc + py))   # 8 отражений точки + сдвиг на центр
        if log is not None:
            log.append(f"{x:4} | {y:4} | {d:4} | {'y - 1' if d >= 0 else 'y тот же'}")
        if d < 0:                               # ближе A: y тот же
            d += 4 * x + 6
        else:                                   # ближе B: y - 1
            d += 4 * (x - y) + 10               # в формуле старый y, поэтому y меняем после
            y -= 1
        x += 1                                  # x растет всегда
    return list(dict.fromkeys(points))          # убираем повторы на осях и диагоналях, порядок сохраняется
